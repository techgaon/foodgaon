const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('src/lib/celebrations.js', 'utf8').replace(/export /g, '');
const api = vm.runInNewContext(source + '\n({ localDate, validPastDate, celebrationMessages })');
assert.equal(api.validPastDate('2024-02-29', '2026-11-01'), true);
assert.equal(api.validPastDate('2023-02-29', '2026-11-01'), false);
assert.equal(api.validPastDate('2026-11-02', '2026-11-01'), false);
assert.equal(api.validPastDate('', '2026-11-01'), true);
assert.equal(api.localDate(new Date(2026, 10, 1, 0, 1)), '2026-11-01');
const profile = { name: 'सीमा', birthday: '1990-11-01', anniversary: '2010-11-01', family: [{name:'आरव', relation:'child', birthday:'2018-11-01'}, {name:'सुमन', birthday:'1980-11-02'}] };
const wishes = api.celebrationMessages(profile, '2026-11-01');
assert.equal(wishes.length, 3);
assert.ok(wishes.some(w => w.text.includes('आरव जी')));
assert.equal(new Set(wishes.map(w => w.id)).size, 3);
assert.equal(api.celebrationMessages({...profile, celebrationsEnabled:false}, '2026-11-01').length, 0);
assert.equal(api.celebrationMessages(null, '2026-11-01').length, 0);
assert.equal(api.celebrationMessages({name:'X',birthday:'2027-11-01'},'2026-11-01').length,0);
assert.equal(api.celebrationMessages({name:'X',birthday:'2024-02-29'},'2026-02-28').length,0);
console.log('PASS: local dates, leap-day validation, future dates, birthdays, anniversaries, family names and opt-out.');
