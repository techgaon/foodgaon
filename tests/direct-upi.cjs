const esbuild = require('esbuild');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const code = esbuild.buildSync({entryPoints:['src/lib/directUpi.js'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
const context = {module:{exports:{}}, URL, URLSearchParams}; vm.runInNewContext(code,context);
const {merchantFor,readMerchantUri,directUpiLink,upiClaim,PARAG_UPI_URI} = context.module.exports;
const parag = merchantFor({id:'parag'});
assert.equal(parag.vpa,'Q182934791@ybl');
assert.equal(parag.name,'PhonePeMerchant');
assert.equal(parag.mcc,'0000','MCC exactly as printed in the PhonePe QR');
assert.equal(parag.mode,'02');
assert.equal(parag.purpose,'00');
assert.equal(merchantFor({id:'another-shop'}),null);
assert.equal(merchantFor({id:'parag',directUpi:{enabled:false}}),null);
const uri = new URL(directUpiLink(parag,122.5,'order123'));
assert.equal(uri.searchParams.get('pa'),parag.vpa);
assert.equal(uri.searchParams.get('am'),'122.50');
assert.equal(uri.searchParams.has('tr'),false,'No tr for small merchants');
assert.equal(uri.searchParams.get('cu'),'INR');
assert.equal(uri.searchParams.get('mc'),'0000');
assert.equal(uri.searchParams.get('mode'),'02');
assert(directUpiLink(parag,122.5,'order123').includes('pa=Q182934791@ybl'),'@ must not be encoded');
assert.equal(directUpiLink(parag,122.5,'order123','plain'),PARAG_UPI_URI,'plain = QR exactly as printed');
const noMcc = readMerchantUri('upi://pay?pa=another@bank&pn=Another');
assert.equal(new URL(directUpiLink(noMcc,10,'other123')).searchParams.has('mc'),false,'Do not assign Parag MCC to other merchants');
const m = readMerchantUri('upi://pay?pa=shop@bank&pn=Shop&mc=5812&am=1&tr=OLD&sign=INVALID&url=https://bad.example');
const fresh = new URL(directUpiLink(m,999,'new123'));
assert.equal(fresh.searchParams.get('mc'),'5812');
assert.equal(fresh.searchParams.get('am'),'999.00');
assert.equal(fresh.searchParams.has('tr'),false);
assert.equal(fresh.searchParams.has('am'),true);
assert.equal(fresh.searchParams.has('sign'),false);
assert.equal(fresh.searchParams.has('url'),false);
for (const bad of ['https://pay?pa=a@bank','upi://pay?pa=bad','upi://pay?pa=shop@bank&mc=12','upi://pay?pa=shop@bank&pa=other@bank','upi://pay?pa=shop@bank&mc=5812&mc=1234']) assert.throws(()=>readMerchantUri(bad));
for (const amount of [0,-1,NaN,Infinity]) assert.throws(()=>directUpiLink(parag,amount,'order123'));
assert.throws(()=>directUpiLink(parag,10,'ref&pa=other'));
const claim = upiClaim({status:'SUCCESS', txnId:'tx123', txnRef:'order123',approvalRef:'UTR123'});
assert.equal(claim.upiRef,'UTR123');
assert.equal(upiClaim({txnRef:'order123'}).upiRef,'','Order reference must never be labelled UTR');
assert(!Object.hasOwn(claim,'paid'),'App callback cannot mark payment received');
assert.equal(readMerchantUri(PARAG_UPI_URI).vpa,parag.vpa);
console.log('PASS: Parag QR, merchant isolation, MCC, amount/ref validation, malicious/stale QR parameters, untrusted callback and UTR separation.');
